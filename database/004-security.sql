CREATE TABLE IF NOT EXISTS Usuario (
 id_usuario INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, nome VARCHAR(150) NOT NULL, email VARCHAR(254) NOT NULL UNIQUE,
 senha_hash VARCHAR(255) NOT NULL, perfil ENUM('administrador','recepcao','profissional','financeiro','estoque') NOT NULL,
 id_profissional INT UNSIGNED NULL, permissoes JSON NULL, ativo BOOLEAN NOT NULL DEFAULT TRUE,
 criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(id_profissional) REFERENCES Profissional(id_profissional)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS SessaoUsuario (
 token_hash CHAR(64) PRIMARY KEY, id_usuario INT UNSIGNED NOT NULL, csrf_token VARCHAR(64) NOT NULL,
 expira_em DATETIME NOT NULL, criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(id_usuario) REFERENCES Usuario(id_usuario), INDEX(expira_em)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS RecuperacaoSenha (
 token_hash CHAR(64) PRIMARY KEY,id_usuario INT UNSIGNED NOT NULL,expira_em DATETIME NOT NULL,utilizado_em DATETIME NULL,
 FOREIGN KEY(id_usuario) REFERENCES Usuario(id_usuario)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS LimiteAcesso (chave CHAR(64) PRIMARY KEY,tentativas INT UNSIGNED NOT NULL, expira_em DATETIME NOT NULL) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS AuditoriaSeguranca (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,id_usuario INT UNSIGNED NULL,acao VARCHAR(100) NOT NULL,recurso VARCHAR(100) NULL,
 criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, INDEX(criado_em), FOREIGN KEY(id_usuario) REFERENCES Usuario(id_usuario)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS EmailOutbox (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,destinatario VARCHAR(254) NOT NULL,assunto VARCHAR(150) NOT NULL,
 conteudo TEXT NOT NULL,status ENUM('pendente','enviado','erro') NOT NULL DEFAULT 'pendente',criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,enviado_em DATETIME NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS FotoClinica (
 id_foto INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,id_atendimento INT UNSIGNED NOT NULL,id_usuario INT UNSIGNED NOT NULL,
 arquivo VARCHAR(80) NOT NULL UNIQUE,mime VARCHAR(30) NOT NULL,tamanho INT UNSIGNED NOT NULL,consentimento TEXT NOT NULL,
 criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(id_atendimento) REFERENCES Atendimento(id_atendimento),FOREIGN KEY(id_usuario) REFERENCES Usuario(id_usuario)
) ENGINE=InnoDB;
